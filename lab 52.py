import numpy as np
from scipy import stats

# Исходные данные из Таблицы 1.6
# x - Среднедушевой прожиточный минимум
x = np.array([78, 82, 87, 79, 89, 106, 67, 88, 73, 87, 76, 115])
# y - Среднедневная заработная плата
y = np.array([133, 148, 134, 154, 162, 195, 139, 158, 152, 162, 159, 173])
n = len(x)

print("--- РЕЗУЛЬТАТЫ ВЫЧИСЛЕНИЙ ---\n")

# =====================================================================
# 1. Построить линейное уравнение парной регрессии y от x
# =====================================================================
# Используем scipy.stats.linregress для быстрого получения параметров
slope, intercept, r_value, p_value, std_err = stats.linregress(x, y)
b = slope
a = intercept

print("1. УРАВНЕНИЕ РЕГРЕССИИ:")
print(f"Уравнение регрессии: y = {a:.2f} + {b:.2f}*x\n")


# =====================================================================
# 2. Рассчитать линейный коэффициент корреляции и среднюю ошибку аппроксимации
# =====================================================================
# Расчет теоретических (предсказанных) значений y
y_pred = a + b * x

# Средняя ошибка аппроксимации (в процентах)
A_mean = np.mean(np.abs((y - y_pred) / y)) * 100

print("2. КОРРЕЛЯЦИЯ И ОШИБКА АППРОКСИМАЦИИ:")
print(f"Линейный коэффициент парной корреляции (r): {r_value:.4f}")
# Дополнительно выведем коэффициент детерминации R^2
print(f"Коэффициент детерминации (R^2): {r_value**2:.4f} (модель объясняет {r_value**2*100:.1f}% дисперсии y)")
print(f"Средняя ошибка аппроксимации (A_ср): {A_mean:.2f}%\n")


# =====================================================================
# 3. Оценить статистическую значимость параметров
# =====================================================================
alpha = 0.05
df = n - 2 # Степени свободы

# Расчет дисперсий для ручной оценки по t-критерию (как в учебниках)
x_mean = np.mean(x)
ss_x = np.sum((x - x_mean)**2) # Сумма квадратов отклонений x
s2_res = np.sum((y - y_pred)**2) / df # Остаточная дисперсия

# Стандартные ошибки параметров
sa = np.sqrt(s2_res * (1/n + (x_mean**2)/ss_x)) # Ошибка параметра a
sb = np.sqrt(s2_res / ss_x)                     # Ошибка параметра b
sr = np.sqrt((1 - r_value**2) / df)             # Ошибка коэффициента корреляции

# t-статистики (фактические значения)
ta = abs(a) / sa
tb = abs(b) / sb
tr = abs(r_value) / sr

# Критическое значение t-критерия Стьюдента (двустороннее)
t_crit = stats.t.ppf(1 - alpha/2, df)

# F-критерий Фишера для оценки модели в целом
F_fact = (r_value**2 / (1 - r_value**2)) * df
F_crit = stats.f.ppf(1 - alpha, 1, df)

print("3. СТАТИСТИЧЕСКАЯ ЗНАЧИМОСТЬ (уровень значимости alpha = 0.05):")
print(f"Табличное t-критическое: {t_crit:.3f}")
print(f"t-факт для 'a': {ta:.3f} -> {'Значимо' if ta > t_crit else 'Незначимо'}")
print(f"t-факт для 'b': {tb:.3f} -> {'Значимо' if tb > t_crit else 'Незначимо'}")
print(f"t-факт для 'r': {tr:.3f} -> {'Корреляция значима' if tr > t_crit else 'Корреляция незначима'}")
print("-" * 30)
print(f"Табличное F-критическое: {F_crit:.3f}")
print(f"F-факт: {F_fact:.3f} -> {'Уравнение в целом значимо' if F_fact > F_crit else 'Уравнение незначимо'}\n")


# =====================================================================
# 4. Выполнить прогноз
# =====================================================================
# Прогнозное значение x: 107% от среднего уровня
x_prog = x_mean * 1.07
# Точечный прогноз y
y_prog = a + b * x_prog

print("4. ПРОГНОЗ:")
print(f"Среднее значение x: {x_mean:.2f} руб.")
print(f"Прогнозное значение x (107% от среднего): {x_prog:.2f} руб.")
print(f"Точечный прогноз заработной платы (y_прогн): {y_prog:.2f} руб.\n")


# =====================================================================
# 5. Оценить точность прогноза (ошибка и доверительный интервал)
# =====================================================================
# Стандартная ошибка прогноза
S_prog = np.sqrt(s2_res * (1 + 1/n + ((x_prog - x_mean)**2) / ss_x))

# Предельная ошибка прогноза (половина ширины интервала)
delta_y = t_crit * S_prog

# Доверительный интервал
ci_lower = y_prog - delta_y
ci_upper = y_prog + delta_y

print("5. ТОЧНОСТЬ ПРОГНОЗА:")
print(f"Стандартная ошибка прогноза (S_p): {S_prog:.2f} руб.")
print(f"Предельная ошибка прогноза (Delta_y): {delta_y:.2f} руб.")
print(f"Доверительный интервал прогноза (с надежностью 95%):")
print(f"[{ci_lower:.2f} руб. ; {ci_upper:.2f} руб.]")